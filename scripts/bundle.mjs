/**
 * Bundle each plugin family into a single self-contained ESM file under `dist/`.
 *
 * A plugin registered by URL is downloaded into the consuming project's `_build` cache and
 * imported from there, so it can resolve neither a sibling source file nor an npm package.
 * The bundle step is what makes a multi-file source tree legal: esbuild inlines every
 * relative import and leaves Node built-ins (`node:fs`, `node:path`) external, because those
 * resolve from anywhere.
 *
 * Two rules the bundle must satisfy are asserted by `tests/plugin/bundle.test.mjs` rather
 * than trusted, since either would only surface as a broken build in someone else's
 * repository: no import of a bare specifier survives, and no dependency was inlined.
 *
 * Usage: node scripts/bundle.mjs [--watch]
 */
import fs from 'node:fs';
import { builtinModules } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import * as esbuild from 'esbuild';

export const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

/** The families this repository publishes. Each becomes one release asset. */
export const FAMILIES = [{ name: 'datavis', entry: 'src/index.mjs' }];

/**
 * Node built-ins are the only imports a bundle may keep, in both spellings.
 *
 * Taken from `node:module` rather than written out. A hand-kept list is wrong in two
 * directions at once: it omits the sub-path builtins (`fs/promises`, `path/posix`,
 * `stream/web`) and the prefix-only ones (`node:test`, `node:sqlite`), so esbuild would try
 * to bundle a legal import, and `tests/plugin/bundle.test.mjs` would reject one with a
 * misleading message. `builtinModules` already contains a few prefixed names, hence the
 * branch: prefixing everything blindly would produce `node:node:test`.
 */
export const externals = [
  ...new Set(
    builtinModules.flatMap((name) => (name.startsWith('node:') ? [name] : [name, `node:${name}`])),
  ),
];

/**
 * Build one family.
 *
 * @param {{name: string, entry: string}} family
 * @param {{watch?: boolean, outdir?: string}} [options]
 * @returns {Promise<{name: string, outfile: string, bytes: number}>}
 */
export async function bundleFamily(family, options = {}) {
  const outdir = options.outdir ?? path.join(repoRoot, 'dist');
  const outfile = path.join(outdir, `${family.name}.mjs`);
  const config = {
    entryPoints: [path.join(repoRoot, family.entry)],
    outfile,
    bundle: true,
    platform: 'node',
    format: 'esm',
    target: 'node20',
    external: externals,
    // esbuild writes each inlined file's path into the bundle as a comment, relative to the
    // working directory. Pin that directory, or the bytes change with where the command was
    // run from and "built twice, byte-identical" is only true from the repository root.
    absWorkingDir: repoRoot,
    // Keeping names readable is worth the bytes: when a directive throws during someone
    // else's build, the stack trace is the only diagnostic they have.
    minify: false,
    keepNames: true,
    legalComments: 'inline',
    // Watch mode should say when it rebuilt; a silent rebuild is indistinguishable from none.
    logLevel: options.watch ? 'info' : 'silent',
    banner: {
      js: [
        '// QuantEcon datavis plugin for mystmd — generated by scripts/bundle.mjs.',
        '// Do not edit: edit src/ and run `npm run bundle`.',
        '// https://github.com/QuantEcon/quantecon-plugins.mystmd',
      ].join('\n'),
    },
  };

  if (options.watch) {
    const context = await esbuild.context(config);
    await context.watch();
    return { name: family.name, outfile, bytes: 0 };
  }

  await esbuild.build(config);
  return { name: family.name, outfile, bytes: fs.statSync(outfile).size };
}

/** Build every family. */
export async function bundleAll(options = {}) {
  const results = [];
  for (const family of FAMILIES) results.push(await bundleFamily(family, options));
  return results;
}

/**
 * Whether this module is the script Node was asked to run, as opposed to an import.
 *
 * Compared on real paths: `process.argv[1]` is whatever the user typed, and a path through a
 * symlink would otherwise never equal the module's own URL, leaving a `node link/scripts/
 * bundle.mjs` to exit 0 having built nothing.
 */
function runAsScript() {
  if (!process.argv[1]) return false;
  try {
    return fs.realpathSync(process.argv[1]) === fs.realpathSync(fileURLToPath(import.meta.url));
  } catch {
    return false;
  }
}

if (runAsScript()) {
  const watch = process.argv.includes('--watch');
  const results = await bundleAll({ watch });
  for (const result of results) {
    const where = path.relative(repoRoot, result.outfile);
    console.log(watch ? `watching → ${where}` : `${where}  ${result.bytes} bytes`);
  }
}
